export function getFidelityTier(score: number): {
  label: string;
  tier: string;
  accent: string;
} {
  if (score >= 90) return { label: 'Canonical Gospel', tier: 'Near-Literal', accent: 'text-emerald-400' };
  if (score >= 75) return { label: 'Faithful Translation', tier: 'True to Spirit', accent: 'text-emerald-300' };
  if (score >= 55) return { label: 'Balanced Adaptation', tier: 'Smart Pruning', accent: 'text-amber-300' };
  if (score >= 35) return { label: 'Loose Interpretation', tier: 'Heavy Revisions', accent: 'text-orange-400' };
  return { label: 'In Name Only', tier: 'Apostasy', accent: 'text-rose-400' };
}

export function getQualityTier(score: number): {
  label: string;
  accent: string;
} {
  if (score >= 90) return { label: 'Masterpiece', accent: 'text-amber-300' };
  if (score >= 75) return { label: 'Certified Great', accent: 'text-sky-300' };
  if (score >= 50) return { label: 'Mixed / Passable', accent: 'text-stone-300' };
  return { label: 'Rotten Failure', accent: 'text-rose-400' };
}

